String? lookupWord(String word, Map<String, String> custom) {
  final clean = word
      .toLowerCase()
      .replaceAll(RegExp(r"[^a-z']"), '')
      .trim();
  if (clean.isEmpty) return null;
  if (custom.containsKey(clean)) return custom[clean];
  return offlineDictionary[clean];
}
